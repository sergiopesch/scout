#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { chmodSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const localConfigurationPath = resolve(".scout-development.mk");

export function parseAppleDevelopmentIdentities(output) {
  const identities = [];
  const pattern = /Apple Development:[^\n]*\(([A-Z0-9]{10})\)/gu;
  for (const match of output.matchAll(pattern)) {
    if (!identities.includes(match[1])) identities.push(match[1]);
  }
  return identities;
}

export function selectDevelopmentTeam(identities, requestedTeam = "") {
  if (requestedTeam) {
    if (!/^[A-Z0-9]{10}$/u.test(requestedTeam)) {
      throw new Error("SCOUT_DEVELOPMENT_TEAM must be a 10-character Apple team identifier");
    }
    if (!identities.includes(requestedTeam)) {
      throw new Error(`No valid Apple Development identity is installed for team ${requestedTeam}`);
    }
    return requestedTeam;
  }
  if (identities.length === 0) {
    throw new Error("No valid Apple Development signing identity is installed");
  }
  if (identities.length > 1) {
    throw new Error(
      `Multiple Apple Development teams are installed (${identities.join(", ")}); `
      + "rerun with SCOUT_DEVELOPMENT_TEAM set to the intended team",
    );
  }
  return identities[0];
}

export function developmentMakefile(team) {
  return [
    "# Generated by Scripts/configure-development-signing.mjs; do not commit.",
    `SCOUT_DEVELOPMENT_TEAM := ${team}`,
    "",
  ].join("\n");
}

function installedIdentityOutput() {
  try {
    return execFileSync(
      "/usr/bin/security",
      ["find-identity", "-v", "-p", "codesigning"],
      { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
    );
  } catch (error) {
    return `${error.stdout ?? ""}${error.stderr ?? ""}`;
  }
}

function setupGuidance(error) {
  process.stderr.write(`${error.message}.\n\n`);
  process.stderr.write(
    "Stable signing is required before Scout can launch without repeated Keychain prompts.\n"
      + "1. Open Xcode > Settings > Accounts and add your Apple Account.\n"
      + "2. Select the Scout team, choose Manage Certificates, and add Apple Development.\n"
      + "3. Run `make configure-development-signing` again.\n",
  );
}

function main() {
  const isCheck = process.argv[2] === "--check";
  const requestedTeam = isCheck
    ? (process.argv[3] ?? "").trim()
    : (process.env.SCOUT_DEVELOPMENT_TEAM ?? "").trim();
  try {
    const identities = parseAppleDevelopmentIdentities(installedIdentityOutput());
    const team = selectDevelopmentTeam(identities, requestedTeam);
    if (isCheck) {
      process.stdout.write(`Scout development signing is ready for team ${team}.\n`);
      return;
    }
    writeFileSync(localConfigurationPath, developmentMakefile(team), { mode: 0o600 });
    chmodSync(localConfigurationPath, 0o600);
    process.stdout.write(
      `Configured stable Scout development signing for team ${team}. `
        + "This machine-local file contains no secret.\n",
    );
  } catch (error) {
    setupGuidance(error);
    process.exitCode = 1;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main();
}
